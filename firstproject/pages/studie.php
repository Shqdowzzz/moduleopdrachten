            <h2>Scriptie & Tips</h2>

            <p>1. Planning & Structuur</p>
            <p>-Hanteer een vaste routine: Werk bijvoorbeeld elke dag 2 tot 4 uur gefocust in plaats van één keer per week een hele dag. Dit houdt de vaart in</p>
            <p>-Maak een globale opzet: Schrijf eerst een inhoudsopgave uit en vul deze per hoofdstuk aan met de belangrijkste onderwerpen</p>
            <p>-Accepteer dat het niet meteen perfect is: Ga gewoon 'breinloos' schrijven als je vastzit; finetunen en herschrijven doe je later wel</p>

            <p>2. Onderzoek & Schrijven</p>
            <p>-Houd direct je bronnnen bij: Zet elke geciteerde bron direct in een literatuurlijst en gebruik een programma zoals Mendeley of Zotero om het overzicht te bewaren</p>
            <p>-Kies een interessant onderwerp: je bent er al snel 3 tot 6 maanden mee bezig. Kies iets waar je affiniteit mee hebt, dat motiveer enorm</p>
            <p>-Lees voorbeelden: Vraag je begeleiders om goed beoordeelde scripties van oud-studenten; zo zie je precies wat er qua opbouw van je verwacht wordt</p>

            <p>3. Samenwerking & Feedback</p>
            <p>-Communiceer met je begeleider: Zie je begeleider als een sparringpartner, niet alleen als beoordelaar. Vraag tijdig om feeback</p>
            <p>-Wees niet bang voor feedback: Feedback is een kans om je werk te verbeteren. Wees open voor suggesties en verbeterpunten</p>

