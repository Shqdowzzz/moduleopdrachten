  <h1>Financiën</h1>

  <h2>💰 Studiefinanciering (DUO)</h2>
  <p>
    Als student kun je studiefinanciering aanvragen via 
    <a href="https://duo.nl/particulier/">DUO</a>. Dit kan bestaan uit een basisbeurs, aanvullende beurs, lening en een studentenreisproduct.
    De hoogte hangt af van je situatie, zoals of je thuis of op kamers woont en het inkomen van je ouders.
    Zorg dat je dit op tijd aanvraagt om geen geld mis te lopen via 
    <a href="https://duo.nl/particulier/studiefinanciering/">studiefinanciering</a>.
  </p>

  <h2>🏠 Wonen en huurkosten</h2>
  <p>
    Veel studenten wonen op kamers of in een studentenhuis. Huurprijzen verschillen per stad en woning.
    Naast huur heb je vaak extra kosten zoals gas, water, licht en servicekosten.
    Soms kun je 
    <a href="https://www.belastingdienst.nl/wps/wcm/connect/nl/huurtoeslag/huurtoeslag">huurtoeslag</a>
    aanvragen als je aan de voorwaarden voldoet.
  </p>

  <h2>💳 Lenen en schulden</h2>
  <p>
    Je kunt geld lenen via <a href="https://duo.nl/particulier/">DUO</a>, maar dit moet later worden terugbetaald.
    Leen alleen wat je echt nodig hebt om problemen na je studie te voorkomen.
    Maak een overzicht van je inkomsten en uitgaven om grip te houden op je geld.
  </p>

  <h2>🧾 Toeslagen</h2>
  <p>
    Als student kun je recht hebben op toeslagen zoals 
    <a href="https://www.belastingdienst.nl/wps/wcm/connect/nl/toeslagen/toeslagen">zorgtoeslag</a> en huurtoeslag.
    Deze toeslagen helpen om vaste kosten beter te betalen.
    Controleer altijd of je recht hebt op extra ondersteuning via de 
    <a href="https://www.belastingdienst.nl">Belastingdienst</a>.
  </p>

  <h2>💼 Bijbaantje</h2>
  <p>
    Veel studenten hebben een bijbaan naast hun studie.
    Dit helpt om extra geld te verdienen en werkervaring op te doen.
    Let er wel op dat je studie niet onder je werk lijdt.
    Je kunt hierbij ook informatie vinden over inkomsten en regels via de 
    <a href="https://www.belastingdienst.nl">Belastingdienst</a>.
  </p>

  <h2>📊 Budgetteren</h2>
  <p>
    Budgetteren betekent dat je je geld goed plant.
    Maak een overzicht van je inkomsten zoals DUO en werk, en je vaste kosten zoals huur en verzekering.
    Zo voorkom je dat je te veel uitgeeft en kun je beter omgaan met je 
    <a href="https://duo.nl/particulier/studieschuld-terugbetalen/overzicht-studieschuld.jsp">studieschuld</a>.
  </p>

  <h2>💡 Geld besparen</h2>
  <p>
    Studenten kunnen op veel manieren geld besparen.
    Denk aan tweedehands spullen kopen, studentenkorting gebruiken, zelf koken en gratis studiemateriaal gebruiken.
    Ook kun je via 
    <a href="https://www.studentenkorting.nl">studentenkorting</a>
    aanbiedingen vinden.
  </p>

  <h2>🧑‍⚖️ Belasting en regels</h2>
  <p>
    Als student kun je soms geld terugkrijgen via belastingaangifte bij de 
    <a href="https://www.belastingdienst.nl">Belastingdienst</a>.
    Het is slim om elk jaar te controleren of je recht hebt op teruggave.
    Ook DUO-leningen en inkomsten kunnen invloed hebben op je belasting en 
    <a href="https://duo.nl/particulier/studieschuld-terugbetalen/overzicht-studieschuld.jsp">studieschuld</a>.
  </p>

