  <h1>🏠 Wonen</h1>

  <p>
    Wonen als student kan een grote uitdaging zijn, vooral in steden waar kamers schaars en duur zijn.
    Op deze pagina vind je informatie over het zoeken van een kamer, kosten en belangrijke zaken waar je op moet letten.
  </p>

  <h2>🏡 Kamer zoeken</h2>
  <p>
    Het vinden van een studentenkamer kan tijd kosten. Begin daarom op tijd met zoeken, vaak al voordat je gaat studeren of in het eerste studiejaar.
    Je kunt kamers vinden via websites, via je school, of via studentenhuizen en hospita’s.
    Reageer snel op advertenties, want kamers worden vaak snel verhuurd.
  </p>

  <h2>💰 Huur en kosten</h2>
  <p>
    De huur van een studentenkamer verschilt per stad en type woning.
    Naast de kale huur betaal je vaak ook servicekosten en kosten voor gas, water en licht.
    Het is belangrijk om vooraf te weten wat je totaal per maand kwijt bent, zodat je niet voor verrassingen komt te staan.
  </p>

  <h2>🧾 Huurtoeslag</h2>
  <p>
    Sommige studenten hebben recht op huurtoeslag. Dit hangt af van je huurprijs, inkomen en woonsituatie.
    Huurtoeslag kan helpen om je maandelijkse kosten te verlagen, dus het is goed om te checken of je hiervoor in aanmerking komt.
  </p>

  <h2>⚠️ Huisregels en contract</h2>
  <p>
    Als je een kamer huurt, krijg je meestal een huurcontract. Lees dit goed door voordat je tekent.
    Let op zaken zoals opzegtermijn, borg en regels in huis. Sommige studentenhuizen hebben huisregels die je moet volgen.
  </p>

  <h2>🧍‍♂️ Alleen of samen wonen</h2>
  <p>
    Je kunt kiezen om alleen te wonen of in een studentenhuis met anderen.
    Samen wonen is vaak goedkoper en gezelliger, maar je deelt ook ruimtes zoals keuken en badkamer.
    Alleen wonen geeft meer rust en privacy, maar is meestal duurder.
  </p>

  <h2>💡 Tips voor studenten</h2>
  <p>
    Begin op tijd met zoeken. Reageer snel op kamers. Check altijd het huurcontract.
    Let op bijkomende kosten en vraag hulp aan je school of studentenvereniging als je vastloopt.
  </p>

